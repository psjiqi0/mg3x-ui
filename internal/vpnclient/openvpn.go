// openvpnFiles 是生成的三个文件的内容（纯数据，可单测）。
type openvpnFiles struct {
	config   string // client.ovpn
	authTxt  string // auth.txt（password 认证时非空）
	upScript string // up.sh：记录 tun 接口名
}

// buildOpenVPNFiles 生成 client.ovpn / auth.txt / up.sh 的内容。纯函数，可单测。
//
// 关键 flags（面板生成，用户不可改，防手滑；RELAY_DESIGN.md §5.1）：
//   - route-nopull + pull-filter ignore "redirect-gateway"：不接受对端推送的网关
//     （双保险），默认路由碰不得；
//   - pull-filter ignore "dhcp-option DNS"：不接受对端 DNS；
//   - route <lanSubnet> vpn_gateway：只路由路由器内网段。
func buildOpenVPNFiles(link model.RouterLink, auth routerAuth, dir string) (openvpnFiles, error) {
	var f openvpnFiles
	proto := link.Proto
	if proto == "" {
		proto = "udp"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# AUTO-GENERATED by 3x-ui vpnclient for RouterLink %d (%s). DO NOT EDIT.\n", link.Id, link.Name)
	b.WriteString("# 铁律：route-nopull + pull-filter，不接受对端推送的网关/DNS；只路由 LanSubnet。\n")
	b.WriteString("client\ndev tun\n")
	fmt.Fprintf(&b, "proto %s\n", proto)
	fmt.Fprintf(&b, "remote %s %d\n", link.RemoteHost, link.RemotePort)
	b.WriteString("route-nopull\n")
	b.WriteString("pull-filter ignore \"redirect-gateway\"\n")
	b.WriteString("pull-filter ignore \"dhcp-option DNS\"\n")
	if strings.Contains(link.LanSubnet, ":") {
		fmt.Fprintf(&b, "route-ipv6 %s\n", link.LanSubnet)
	} else {
		// CIDR 转 "network netmask" 形式，兼容老版本 openvpn 的 route 指令。
		_, ipnet, err := net.ParseCIDR(link.LanSubnet)
		if err != nil {
			return f, fmt.Errorf("openvpn: lanSubnet 非法: %w", err)
		}
		fmt.Fprintf(&b, "route %s %s vpn_gateway\n", ipnet.IP.String(), net.IP(ipnet.Mask).String())
	}
	// data-ciphers：2026-10-14 PROSCEND 实测——服务端只支持 AES-256-CBC，
	// 新版客户端默认 data-ciphers 不含 CBC 会报 "failed to negotiate cipher"。
	// 这是客户端的候选列表（GCM 优先），对支持 GCM 的服务端无影响。
	b.WriteString("data-ciphers AES-256-GCM:AES-128-GCM:AES-256-CBC\n")
	b.WriteString("persist-tun\npersist-key\nkeepalive 10 60\nconnect-retry 5 30\n")
	// 注意：设计文档 §5.1 的 `remap` 不是合法 openvpn 指令（实测 openvpn 2.6.19
	// 只有 --remap-usr1），写了会导致 openvpn 启动直接失败，故省略。
	switch auth.Type {
	case "cert":
		if strings.TrimSpace(auth.CA) == "" || strings.TrimSpace(auth.Cert) == "" || strings.TrimSpace(auth.Key) == "" {
			return f, errors.New("openvpn: cert 认证缺少 ca/cert/key")
		}
		fmt.Fprintf(&b, "<ca>\n%s\n</ca>\n<cert>\n%s\n</cert>\n<key>\n%s\n</key>\n",
			strings.TrimSpace(auth.CA), strings.TrimSpace(auth.Cert), strings.TrimSpace(auth.Key))
	default: // "password" 或未填：用户名密码认证
		if strings.TrimSpace(auth.Username) == "" || strings.TrimSpace(auth.Password) == "" {
			return f, errors.New("openvpn: password 认证缺少 username/password")
		}
		f.authTxt = auth.Username + "\n" + auth.Password + "\n"
		fmt.Fprintf(&b, "auth-user-pass %s\n", filepath.Join(dir, "auth.txt"))
	}
	// 管理接口：unix socket（免去 per-连接分配 TCP 端口的冲突管理）。
	fmt.Fprintf(&b, "management %s unix\n", filepath.Join(dir, "mgmt.sock"))
	b.WriteString("script-security 2\n")
	// up 脚本只记录 $dev（tun 接口名），不碰任何路由/DNS。
	// openvpn 无 --dev-name（实测 2.6.19），这是把接口名关联回连接 id 的确定性手段。
	fmt.Fprintf(&b, "up %s\n", filepath.Join(dir, "up.sh"))
	f.config = b.String()
	f.upScript = "#!/bin/sh\n" +
		"# AUTO-GENERATED by 3x-ui vpnclient. 记录 openvpn 分配的 tun 接口名（$dev），\n" +
		"# 供端口转发的 SO_BINDTODEVICE 与状态采集使用。只写文件，不碰任何路由/DNS。\n" +
		"echo \"$dev\" > " + filepath.Join(dir, "ifname") + "\n"
	return f, nil
}

// writeOpenVPNConfigs 写 client.ovpn / auth.txt / up.sh（0600/0700，幂等）。
func writeOpenVPNConfigs(dir string, link model.RouterLink, auth routerAuth) error {
	f, err := buildOpenVPNFiles(link, auth, dir)
	if err != nil {
		return err
	}
	if err := writeFileIfChanged(filepath.Join(dir, "client.ovpn"), f.config, 0600); err != nil {
		return err
	}
	authPath := filepath.Join(dir, "auth.txt")
	if f.authTxt != "" {
		if err := writeFileIfChanged(authPath, f.authTxt, 0600); err != nil {
			return err
		}
	} else {
		_ = os.Remove(authPath) // cert 认证：删掉旧的密码文件，不留 secrets
	}
	return writeFileIfChanged(filepath.Join(dir, "up.sh"), f.upScript, 0700)
}

// dialOVPNLocked 启动 openvpn 子进程（前台运行，Manager 托管；不断线自愈靠
// openvpn 自身的 connect-retry，进程崩溃靠 Manager+job 重启）。
func (m *Manager) dialOVPNLocked(h *linkHandle, link model.RouterLink, auth routerAuth) error {
	logPath := filepath.Join(h.dir, "openvpn.log")
	logF, err := os.OpenFile(logPath, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0600)
	if err != nil {
		return fmt.Errorf("openvpn: 打开日志失败: %w", err)
	}
	cmd := exec.Command("openvpn", "--config", filepath.Join(h.dir, "client.ovpn"))
	cmd.Stdout = logF
	cmd.Stderr = logF
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	proc, err := startChildProc(cmd)
	_ = logF.Close() // 子进程已继承 fd，本端关闭自己的拷贝
	if err != nil {
		return fmt.Errorf("openvpn: 启动失败: %w", err)
	}
	h.proc = proc
	return nil
}

// ovpnMgmtState 是管理接口 state 查询的结果。
type ovpnMgmtState struct {
	state   string // CONNECTED / RECONNECTING / WAIT / AUTH ...
	stateAt int64  // 该状态的时间戳（unix）
	rxBytes int64  // TUN/TAP read bytes
	txBytes int64  // TUN/TAP write bytes
}

// ovpnMgmtQuery 连管理 socket 查 state 与字节计数（短超时，失败不致命）。
func ovpnMgmtQuery(dir string) (ovpnMgmtState, error) {
	var st ovpnMgmtState
	conn, err := net.DialTimeout("unix", filepath.Join(dir, "mgmt.sock"), 3*time.Second)
	if err != nil {
		return st, err
	}
	defer conn.Close()
	_ = conn.SetDeadline(time.Now().Add(5 * time.Second))
	r := bufio.NewReader(conn)

	// 先消费 greeting（>INFO:...）。
	for {
		line, err := r.ReadString('\n')
		if err != nil {
			return st, err
		}
		if strings.HasPrefix(line, ">INFO:") || strings.TrimSpace(line) == "" {
			break
		}
	}
	mgmtCmd := func(cmd string) []string {
		_, _ = fmt.Fprintln(conn, cmd)
		var lines []string
		for {
			line, err := r.ReadString('\n')
			if err != nil {
				break
			}
			line = strings.TrimRight(line, "\r\n")
			if line == "END" {
				break
			}
			lines = append(lines, line)
		}
		return lines
	}
	for _, line := range mgmtCmd("state") {
		line = strings.TrimPrefix(line, ">STATE:")
		f := strings.Split(line, ",")
		if len(f) >= 2 {
			st.state = f[1]
			st.stateAt, _ = strconv.ParseInt(f[0], 10, 64)
		}
	}
	for _, line := range mgmtCmd("status") {
		if v, ok := strings.CutPrefix(line, "TUN/TAP read bytes,"); ok {
			st.rxBytes, _ = strconv.ParseInt(strings.TrimSpace(v), 10, 64)
		}
		if v, ok := strings.CutPrefix(line, "TUN/TAP write bytes,"); ok {
			st.txBytes, _ = strconv.ParseInt(strings.TrimSpace(v), 10, 64)
		}
	}
	return st, nil
}

// probeOVPNLocked 探测 openvpn 隧道状态（m.mu 持有中调用）。
func (m *Manager) probeOVPNLocked(h *linkHandle) {
	if h.proc == nil || !h.proc.running() {
		h.bindIface.Store("") // 进程没了，接口绑定立即失效（egress fail-closed）
		if h.status == StatusUp || h.status == StatusDialing {
			h.status = StatusError
			if err := h.proc.exitError(); err != nil {
				h.message = "openvpn 进程已退出: " + err.Error() + "（见 openvpn.log）"
			} else {
				h.message = "openvpn 进程已退出（见 openvpn.log）"
			}
		}
		return
	}
	st, err := ovpnMgmtQuery(h.dir)
	if err != nil {
		// 管理接口暂时连不上：不断言，保持原状态（启动初期常见）。
		return
	}
	h.rxBytes, h.txBytes = st.rxBytes, st.txBytes
	if name := ovpnIfaceName(h.dir, h.link.LanSubnet); name != "" {
		h.iface = name
		h.bindIface.Store(name)
	}
	switch st.state {
	case "CONNECTED":
		h.status = StatusUp
		h.message = ""
		if st.stateAt > 0 {
			h.handshakeAt = time.Unix(st.stateAt, 0)
		}
	default:
		if h.status == StatusUp {
			h.status = StatusDialing
			h.message = "连接中断，openvpn 正在重连"
		}
	}
}

// ovpnIfaceName 解析本连接的 tun 接口名：优先读 up.sh 写的 ifname 文件
// （确定性），兜底按 LanSubnet 在路由表里找 tun* 接口（单连接无重叠时准确）。
func ovpnIfaceName(dir, lanSubnet string) string {
	if name := readIfnameFile(dir); name != "" {
		if _, err := net.InterfaceByName(name); err == nil {
			return name
		}
	}
	if data, err := os.ReadFile("/proc/net/route"); err == nil {
		if lan, err := netip.ParsePrefix(lanSubnet); err == nil {
			lan = lan.Masked()
			for _, r := range parseProcNetRoute(string(data)) {
				if !strings.HasPrefix(r.Iface, "tun") {
					continue
				}
				rn := netip.PrefixFrom(r.Dest, r.Bits).Masked()
				if rn.Bits() <= lan.Bits() && rn.Contains(lan.Addr()) {
					return r.Iface
				}
			}
		}
	}
	return ""
}

// bindDeviceDialFunc 返回 ovpn/pptp 用的 DialFunc：socket 上做
// SO_BINDTODEVICE，把该连接的转发 socket 钉死在它自己的隧道接口上。
//
// 取舍说明（相对 RELAY_DESIGN.md §8.3 字面）：§8.3 同时提到了
// "net.ListenConfig.Control"（监听侧）与"dial 端同样"。但把公网监听 socket
// 绑到 tunX/pppX 上会让它收不到公网包——监听器必须保持 wildcard 才能服务公网。
// "Linux 对绑定设备的 socket 做设备作用域的路由查找"这一机制只对出方向
// （connect/send）生效，因此设备绑定只做在 dial 侧，这正是解决"多连接内网段
// 重叠串流"的关键。监听侧不绑。
//
// 接口名在拨号初期可能未知：iface 是 atomic 指针，每次拨号时读取当前值；
// 未知时退化为普通 dial（路由表无重叠时依然正确），发现接口后自动钉住。
func bindDeviceDialFunc(iface *atomic.Value) DialFunc {
	return func(ctx context.Context, network, address string) (net.Conn, error) {
		name, _ := iface.Load().(string)
		d := &net.Dialer{Timeout: fwdDialTimeout}
		if name != "" {
			d.Control = func(_, _ string, c syscall.RawConn) error {
				var opErr error
				ctrlErr := c.Control(func(fd uintptr) {
					opErr = unix.SetsockoptString(int(fd), unix.SOL_SOCKET, unix.SO_BINDTODEVICE, name)
				})
				if ctrlErr != nil {
					return ctrlErr
				}
				return opErr
			}
		} else {
			logger.Debug("vpnclient: 转发 dial 时隧道接口未知，本次不绑设备")
		}
		return d.DialContext(ctx, network, address)
	}
}
