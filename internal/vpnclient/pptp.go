// buildPPTPOptions 生成 options.pptp 的内容。纯函数，可单测。
//
// 铁律：nodefaultroute（绝不用 defaultroute），noipdefault；
// 不写 usepeerdns（不要对端 DNS）。
func buildPPTPOptions(link model.RouterLink) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# AUTO-GENERATED by 3x-ui vpnclient for RouterLink %d (%s). DO NOT EDIT.\n", link.Id, link.Name)
	b.WriteString("# 铁律：nodefaultroute —— 绝不碰默认路由。\n")
	b.WriteString("nodefaultroute\n")
	b.WriteString("noipdefault\n")
	switch link.Mppe {
	case "require-mppe":
		b.WriteString("require-mppe\n")
		// 见下：只要档位是 require-mppe* 就必须带 mppe-stateful。
		b.WriteString("mppe-stateful\n")
	case "nomppe":
		b.WriteString("# MPPE disabled by panel option\n")
	default: // "require-mppe-128" 或空：默认最强档
		b.WriteString("require-mppe-128\n")
		// 实测（2026-10-14，真机路由器 116.59.15.247）：该路由器要求 MPPE 128-bit
		// stateful；只给 require-mppe-128 会卡在 CCP 协商，加上 mppe-stateful 后
		// 一次通过。只要 Mppe 档位是 require-mppe* 就必须同时写这一行。
		b.WriteString("mppe-stateful\n")
	}
	// noauth 是"不要求对端认证我方"，不是免密；我方认证走 chap-secrets。
	b.WriteString("noauth\n")
	return b.String()
}

// chapSecretsLine 生成该连接的 chap-secrets 行：
//
//	<username> rl-<id> <password> *
//
// 第二字段 remotename 取 linkname（rl-<id>），与 pppd 命令行的 remotename 对应。
func chapSecretsLine(link model.RouterLink, auth routerAuth) string {
	if strings.TrimSpace(auth.Username) == "" {
		return ""
	}
	return fmt.Sprintf("%s %s %s *\n",
		pppWord(auth.Username), "rl-"+strconv.Itoa(link.Id), pppWord(auth.Password))
}

// pppWord：含空白/引号/反斜杠的字段加双引号（pppd chap-secrets 词法）。
func pppWord(s string) string {
	if strings.ContainsAny(s, " \t\"\\") {
		return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
	}
	return s
}

// chapSecretsPath 是多连接共用的 chap-secrets 路径（pppd 支持多行）。
func chapSecretsPath(baseDir string) string {
	_ = baseDir
	return "/etc/ppp/chap-secrets"
}

// syncChapSecrets 幂等维护 chap-secrets：先删掉该 id 的旧行，再追加新行；
// line == "" 时只删除（Remove 路径）。文件 0600。
func syncChapSecrets(path string, id int, line string) error {
	tag := "rl-" + strconv.Itoa(id)
	var lines []string
	if data, err := os.ReadFile(path); err == nil {
		for _, l := range strings.Split(string(data), "\n") {
			if strings.TrimSpace(l) == "" {
				continue
			}
			if f := strings.Fields(l); len(f) >= 2 && f[1] == tag {
				continue
			}
			lines = append(lines, l)
		}
	}
	if strings.TrimSpace(line) != "" {
		lines = append(lines, strings.TrimSpace(line))
	}
	out := ""
	if len(lines) > 0 {
		out = strings.Join(lines, "\n") + "\n"
	}
	if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(out), 0600)
}

// ensurePPTPRouteScripts 安装 /etc/ppp/ip-up.d/rl-route 与 ip-down.d/rl-route
// （面板安装、幂等；RELAY_DESIGN.md §6.1）。
//
// 脚本只做两件事：① 把 $IFNAME（pppX）写进连接目录的 ifname 文件，供 Manager
// 做 SO_BINDTODEVICE 绑定与状态采集（用 linkname rl-<id> 关联回连接 id）；
// ② 加/删该连接 LanSubnet 的 scoped 路由。绝不写默认路由/DNS。
//
// 注意：这是主路径；Manager 侧还有兜底（discoverPPTPIface + ensureScopedRoute），
// 覆盖 ip-up.d 不被执行的发行版。
var pptpScriptsInstalled = struct {
	sync.Mutex
	done map[string]bool
}{done: map[string]bool{}}

func ensurePPTPRouteScripts(baseDir string) {
	pptpScriptsInstalled.Lock()
	if pptpScriptsInstalled.done[baseDir] {
		pptpScriptsInstalled.Unlock()
		return
	}
	pptpScriptsInstalled.done[baseDir] = true
	pptpScriptsInstalled.Unlock()

	up := `#!/bin/sh
# AUTO-GENERATED by 3x-ui vpnclient. 只加本连接 LanSubnet 的 scoped 路由；绝不碰默认路由/DNS。
# LINKNAME=rl-<id>，IFNAME=pppX，由 pppd 传入。
case "$LINKNAME" in rl-*) ;; *) exit 0 ;; esac
id="${LINKNAME#rl-}"
f="` + baseDir + `/$id/lan-subnet"
[ -f "$f" ] || exit 0
subnet=$(cat "$f" 2>/dev/null)
[ -n "$subnet" ] || exit 0
echo "$IFNAME" > "` + baseDir + `/$id/ifname"
ip route replace "$subnet" dev "$IFNAME" 2>/dev/null || true
`
	down := `#!/bin/sh
# AUTO-GENERATED by 3x-ui vpnclient. 删除本连接的 scoped 路由（反向清理）。
case "$LINKNAME" in rl-*) ;; *) exit 0 ;; esac
id="${LINKNAME#rl-}"
f="` + baseDir + `/$id/lan-subnet"
[ -f "$f" ] || exit 0
subnet=$(cat "$f" 2>/dev/null)
[ -n "$subnet" ] || exit 0
ip route del "$subnet" dev "$IFNAME" 2>/dev/null || true
`
	if err := writeFileIfChanged("/etc/ppp/ip-up.d/rl-route", up, 0755); err != nil {
		logger.Warningf("vpnclient: 安装 pptp ip-up 脚本失败（Manager 兜底仍会补路由）: %v", err)
		return
	}
	if err := writeFileIfChanged("/etc/ppp/ip-down.d/rl-route", down, 0755); err != nil {
		logger.Warningf("vpnclient: 安装 pptp ip-down 脚本失败: %v", err)
	}
}

// writePPTPConfigsLocked 写 options.pptp / lan-subnet，同步 chap-secrets 行，
// 安装路由脚本（幂等）。
func (m *Manager) writePPTPConfigsLocked(h *linkHandle, link model.RouterLink, auth routerAuth) error {
	if err := writeFileIfChanged(
		filepath.Join(h.dir, "options.pptp"), buildPPTPOptions(link), 0600); err != nil {
		return err
	}
	if err := writeFileIfChanged(
		filepath.Join(h.dir, "lan-subnet"), strings.TrimSpace(link.LanSubnet)+"\n", 0600); err != nil {
		return err
	}
	if line := chapSecretsLine(link, auth); line != "" {
		if err := syncChapSecrets(chapSecretsPath(m.baseDir), link.Id, line); err != nil {
			return fmt.Errorf("pptp: 写 chap-secrets 失败: %w", err)
		}
	}
	ensurePPTPRouteScripts(m.baseDir)
	return nil
}

// dialPPTPLocked 启动 pppd 子进程（RELAY_DESIGN.md §6.1 的命令，exec 形式）。
func (m *Manager) dialPPTPLocked(h *linkHandle, link model.RouterLink, auth routerAuth) error {
	if strings.TrimSpace(auth.Username) == "" || auth.Password == "" {
		return errors.New("pptp: 缺少 username/password")
	}
	if link.RemotePort != 1723 {
		// pptp(8) 没有端口参数，固定连 TCP 1723；配了别的端口只告警，
		// 不静默连错（pppd 仍会连 1723）。
		logger.Warningf("vpnclient: 连接 %d pptp 只支持 TCP 1723，配置的 remotePort=%d 将被忽略",
			link.Id, link.RemotePort)
	}
	logPath := filepath.Join(h.dir, "pppd.log")
	logF, err := os.OpenFile(logPath, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0600)
	if err != nil {
		return fmt.Errorf("pptp: 打开日志失败: %w", err)
	}
	tag := "rl-" + strconv.Itoa(link.Id)
	cmd := exec.Command("pppd",
		"pty", fmt.Sprintf("pptp %s --nolaunchpppd", link.RemoteHost),
		"name", auth.Username,
		"remotename", tag,
		"linkname", tag, // ip-up 脚本靠 $LINKNAME 关联回连接 id
		"file", filepath.Join(h.dir, "options.pptp"),
		// nodetach：必须前台运行，Manager 才能托管（设计文档的 shell 形式隐含了这点；
		// 否则 pppd daemonize 后 Wait 立即返回，看护失效）。
		"nodetach",
	)
	cmd.Stdout = logF
	cmd.Stderr = logF
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	proc, err := startChildProc(cmd)
	_ = logF.Close()
	if err != nil {
		return fmt.Errorf("pptp: 启动 pppd 失败: %w", err)
	}
	h.proc = proc
	// 拨号前记录已有的 ppp 接口，供兜底发现用。
	h.pppBefore = pppIfaces()
	return nil
}

// discoverPPTPIface 是拨号后的异步兜底发现：等 ip-up 脚本写 ifname 文件
// （主路径），30s 内没等到则用"新增 ppp 接口" diff 认领。找到后补 scoped 路由。
func (m *Manager) discoverPPTPIface(id int, gen uint64) {
	deadline := time.Now().Add(30 * time.Second)
	for time.Now().Before(deadline) {
		m.mu.Lock()
		h := m.links[id]
		if h == nil || h.gen != gen {
			m.mu.Unlock()
			return
		}
		dir, before := h.dir, h.pppBefore
		m.mu.Unlock()

		if name := readIfnameFile(dir); name != "" {
			m.notePPTPIface(id, gen, name, "ip-up 脚本")
			return
		}
		if diff := pppIfaceDiff(before, pppIfaces()); len(diff) == 1 {
			_ = os.WriteFile(filepath.Join(dir, "ifname"), []byte(diff[0]+"\n"), 0600)
			m.notePPTPIface(id, gen, diff[0], "接口 diff 兜底")
			return
		}
		time.Sleep(500 * time.Millisecond)
	}
	logger.Warningf("vpnclient: 连接 %d pptp 接口发现超时（仍在 dialing，ip-up 脚本主路径可能未执行）", id)
}

// notePPTPIface 记录发现的 ppp 接口并补 scoped 路由。
func (m *Manager) notePPTPIface(id int, gen uint64, iface, via string) {
	m.mu.Lock()
	defer m.mu.Unlock()
	h := m.links[id]
	if h == nil || h.gen != gen {
		return
	}
	if _, err := net.InterfaceByName(iface); err != nil {
		return
	}
	h.iface = iface
	h.bindIface.Store(iface)
	logger.Infof("vpnclient: 连接 %d pptp 接口 %s（%s）", id, iface, via)
	if err := ensureScopedRoute(h.link.LanSubnet, iface); err != nil {
		logger.Warningf("vpnclient: 连接 %d 补 scoped 路由: %v", id, err)
	}
}

// probePPTPLocked 探测 pppd 隧道状态（m.mu 持有中调用）。
func (m *Manager) probePPTPLocked(h *linkHandle) {
	if h.proc == nil || !h.proc.running() {
		h.bindIface.Store("") // 进程没了，接口绑定立即失效（egress fail-closed）
		if h.status == StatusUp || h.status == StatusDialing {
			h.status = StatusError
			if err := h.proc.exitError(); err != nil {
				h.message = "pppd 进程已退出: " + err.Error() + "（见 pppd.log）"
			} else {
				h.message = "pppd 进程已退出（见 pppd.log）"
			}
		}
		return
	}
	// 接口发现（同步轻量版：读文件 + 一次 diff，不等待）。
	if h.iface == "" {
		if name := readIfnameFile(h.dir); name != "" {
			if _, err := net.InterfaceByName(name); err == nil {
				h.iface = name
				h.bindIface.Store(name)
			}
		} else if diff := pppIfaceDiff(h.pppBefore, pppIfaces()); len(diff) == 1 {
			h.iface = diff[0]
			h.bindIface.Store(diff[0])
		}
	}
	if h.iface == "" {
		return // 还在拨号
	}
	if _, err := net.InterfaceByName(h.iface); err != nil {
		return // 接口还没起来
	}
	// 防御性复检 scoped 路由（主路径是 ip-up 脚本）。
	if err := ensureScopedRoute(h.link.LanSubnet, h.iface); err != nil {
		logger.Warningf("vpnclient: 连接 %d 补 scoped 路由: %v", h.id, err)
	}
	rx, tx := ifaceBytes(h.iface)
	h.rxBytes, h.txBytes = int64(rx), int64(tx)
	if h.status != StatusUp {
		h.status = StatusUp
		h.message = ""
		if fi, err := os.Stat(filepath.Join(h.dir, "ifname")); err == nil {
			h.handshakeAt = fi.ModTime()
		}
	}
}

// pppIfaces 列出当前全部 ppp* 接口名。
func pppIfaces() []string {
	ifs, err := net.Interfaces()
	if err != nil {
		return nil
	}
	var out []string
	for _, i := range ifs {
		if strings.HasPrefix(i.Name, "ppp") {
			out = append(out, i.Name)
		}
	}
	return out
}

// pppIfaceDiff 返回 after 中不在 before 里的接口（拨号兜底发现用）。
func pppIfaceDiff(before, after []string) []string {
	have := map[string]bool{}
	for _, n := range before {
		have[n] = true
	}
	var out []string
	for _, n := range after {
		if !have[n] {
			out = append(out, n)
		}
	}
	return out
}
